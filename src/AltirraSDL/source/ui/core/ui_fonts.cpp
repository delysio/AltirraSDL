// Build a static glyph range covering Latin-1, Latin Extended, Greek, and
// Cyrillic via ImFontGlyphRangesBuilder.  Persistent storage is required
// because ImGui keeps the pointer until the atlas is built.
static const ImWchar *GetUIFontGlyphRanges() {
	static ImVector<ImWchar> ranges;
	if (ranges.empty()) {
		ImFontGlyphRangesBuilder builder;
		ImFontAtlas *atlas = ImGui::GetIO().Fonts;
		builder.AddRanges(atlas->GetGlyphRangesDefault());   // Basic Latin + Latin-1
		builder.AddRanges(atlas->GetGlyphRangesCyrillic());  // ~400 Cyrillic glyphs
		builder.AddRanges(atlas->GetGlyphRangesGreek());     // Greek + Coptic
		// Latin Extended-A and Extended-B (Western/Central European accents
		// not covered by Latin-1: ą ć ę ł ń ś ź ż ř š č etc.)
		static const ImWchar kLatinExt[] = { 0x0100, 0x024F, 0 };
		builder.AddRanges(kLatinExt);
		// General Punctuation (en-dash, em-dash, smart quotes, ellipsis,
		// bullet, trade/service marks) — common in game pack file names.
		static const ImWchar kPunctuation[] = { 0x2000, 0x206F, 0 };
		builder.AddRanges(kPunctuation);
		// Letterlike Symbols (trademark ™ etc.)
		static const ImWchar kLetterlike[] = { 0x2100, 0x214F, 0 };
		builder.AddRanges(kLetterlike);
		builder.BuildRanges(&ranges);
	}
	return ranges.Data;
}

// Mono font: keep the atlas small — debugger panes display ASCII + a few
// box-drawing chars.  Default range (Basic Latin + Latin-1) is enough.
static const ImWchar *GetMonoFontGlyphRanges() {
	return ImGui::GetIO().Fonts->GetGlyphRangesDefault();
}

// Material Icons font: every glyph lives in the BMP Private Use Area
// (U+E000..U+F8FF).  Loading the full range adds ~2,200 glyphs to the
// atlas — about 350 KB of texture at 22dp on a standard-density screen,
// which is acceptable for the one-time atlas build and keeps every
// ICON_MD_* macro from altirra_icons.h immediately available.
static const ImWchar *GetIconFontGlyphRanges() {
	static const ImWchar kIconRange[] = { 0xE000, 0xF8FF, 0 };
	return kIconRange;
}

static void LoadFontFromFile(const ATFontFile *file, float pixelSize,
	const ImWchar *glyphRanges, ImFont*& out, bool merge = false)
{
	out = nullptr;
	if (!file) return;

	const void *srcData = nullptr;
	size_t srcSize = 0;
	void *sdlData = nullptr;

	if (file->mpBuiltinData) {
		// Embedded blob — point at the linker-provided data directly.
		srcData = file->mpBuiltinData;
		srcSize = file->mBuiltinSize;
	} else {
		sdlData = SDL_LoadFile(file->path.c_str(), &srcSize);
		if (!sdlData || srcSize == 0) {
			LOG_INFO("UI", "Font load failed: %s", file->path.c_str());
			if (sdlData) SDL_free(sdlData);
			return;
		}
		srcData = sdlData;
	}

	// Always copy through ImGui's allocator so FontDataOwnedByAtlas can
	// safely IM_FREE() it later.  Embedded data must NOT be freed; copying
	// keeps that ownership invariant simple.
	void *imgData = IM_ALLOC(srcSize);
	memcpy(imgData, srcData, srcSize);
	if (sdlData) SDL_free(sdlData);

	ImFontConfig cfg;
	cfg.FontDataOwnedByAtlas = true;
	cfg.FontNo = file->fontIndex;
	cfg.MergeMode = merge;

	ImGuiIO& io = ImGui::GetIO();
	out = io.Fonts->AddFontFromMemoryTTF(imgData, (int)srcSize, pixelSize, &cfg, glyphRanges);
}

// Load the embedded Material Icons blob at `pixelSize`.  Returns the
// font through `out`.  Self-contained (no ATFontFile rec needed) because
// the icon font is never user-selectable.
static void LoadIconFontFromMemory(float pixelSize, ImFont*& out) {
	out = nullptr;
	if (!g_atFontMaterialIconsData || g_atFontMaterialIconsData_size == 0) {
		LOG_INFO("UI", "Icon font blob unavailable");
		return;
	}
	void *imgData = IM_ALLOC(g_atFontMaterialIconsData_size);
	memcpy(imgData, g_atFontMaterialIconsData, g_atFontMaterialIconsData_size);

	ImFontConfig cfg;
	cfg.FontDataOwnedByAtlas = true;
	// Icon glyphs are square; ask ImGui to pixel-snap horizontal advance
	// so they align cleanly to the integer grid the buttons draw on.
	cfg.PixelSnapH = true;
	// Material Icons font has tight side-bearings; nudge slightly to
	// match the visual baseline of the body text when drawn side by side.
	cfg.GlyphOffset = ImVec2(0.0f, 1.0f);

	ImGuiIO& io = ImGui::GetIO();
	out = io.Fonts->AddFontFromMemoryTTF(imgData,
		(int)g_atFontMaterialIconsData_size, pixelSize,
		&cfg, GetIconFontGlyphRanges());
}

static void RebuildAtlas() {
	ImGuiIO& io = ImGui::GetIO();
	io.Fonts->Clear();

	const float uiPx   = (float)s_uiSize   * s_contentScale * 96.0f / 72.0f;
	const float monoPx = (float)s_monoSize * s_contentScale * 96.0f / 72.0f;
	const float iconPx = kIconPointSize    * s_contentScale * 96.0f / 72.0f;

	LOG_INFO("UI", "Font rebuild: uiSize=%d monoSize=%d contentScale=%.2f uiPx=%.1f monoPx=%.1f iconPx=%.1f FontGlobalScale=%.2f",
		s_uiSize, s_monoSize, s_contentScale, uiPx, monoPx, iconPx, ImGui::GetIO().FontGlobalScale);

	const ATFontFile *uiFile   = PickFontFile(s_uiFamily.c_str(),   s_uiWeight.c_str());
	const ATFontFile *monoFile = PickFontFile(s_monoFamily.c_str(), s_monoWeight.c_str(), 1);

	LoadFontFromFile(uiFile,   uiPx,   GetUIFontGlyphRanges(),   g_pFontUI);
	if (!g_pFontUI)
		LoadFontFromFile(&s_fontFiles[0], uiPx, GetUIFontGlyphRanges(), g_pFontUI);
	ImFont *merged = nullptr;
	if (g_pFontUI && uiFile != &s_fontFiles[0])
		LoadFontFromFile(&s_fontFiles[0], uiPx, GetUIFontGlyphRanges(), merged, true);
	LoadFontFromFile(monoFile, monoPx, GetMonoFontGlyphRanges(), g_pFontMono);
	if (!g_pFontMono)
		LoadFontFromFile(&s_fontFiles[1], monoPx, GetMonoFontGlyphRanges(), g_pFontMono);
	if (g_pFontMono && monoFile != &s_fontFiles[1])
		LoadFontFromFile(&s_fontFiles[1], monoPx, GetMonoFontGlyphRanges(), merged, true);
	LoadFontFromFile(PickFontFile(s_uiFamily.c_str(), "Bold"), uiPx,
		GetUIFontGlyphRanges(), s_fontHeading);
	if (s_fontHeading)
		LoadFontFromFile(&s_fontFiles[0], uiPx, GetUIFontGlyphRanges(), merged, true);
	LoadIconFontFromMemory(iconPx, g_pFontIcon);

	if (!g_pFontUI) {
		// Last-resort fallback: ImGui's built-in ProggyClean bitmap font.
		// Reached only if every TTF (including the embedded one) failed
		// to load, e.g. due to memory pressure or a corrupted blob.
		LOG_INFO("UI", "All TTF fonts failed to load — using ProggyClean fallback");
		g_pFontUI = io.Fonts->AddFontDefault();
	}
	if (!g_pFontMono) {
		g_pFontMono = g_pFontUI;
	}
	if (!s_fontHeading) s_fontHeading = g_pFontUI;
	// g_pFontIcon may legitimately be null if the icon blob failed to
	// load — callers must always null-check before drawing with it.

	io.FontDefault = g_pFontUI;
	// ImGui 1.92 retains FontSizeBase after the first NewFrame. Replacing
	// FontDefault alone changes the face but leaves menus at the old size.
	ImGui::GetStyle().FontSizeBase = g_pFontUI->LegacySize;
	// ImGui 1.92 renderer backends build and upload the dynamic atlas on
	// their next NewFrame.  Calling Build() here marks all glyphs as
	// preloaded and conflicts once RendererHasTextures is enabled.
}

