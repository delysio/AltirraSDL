static bool EndsWithCI(const VDStringA& s, const char *suffix) {
	const size_t n = strlen(suffix);
	if (s.size() < n) return false;
	for (size_t i = 0; i < n; ++i) {
		char a = (char)tolower((unsigned char)s[s.size() - n + i]);
		char b = (char)tolower((unsigned char)suffix[i]);
		if (a != b) return false;
	}
	return true;
}

// Read actual SFNT metadata in both catalog and directory discovery paths.
static void AddFontFiles(const VDStringA& path) {
	if (!EndsWithCI(path, ".ttf") && !EndsWithCI(path, ".otf")
		&& !EndsWithCI(path, ".ttc") && !EndsWithCI(path, ".otc")) return;
	if (std::any_of(s_fontFiles.begin(), s_fontFiles.end(),
		[&](const ATFontFile& f) { return f.path == path; })) return;
	size_t size = 0;
	void *data = SDL_LoadFile(path.c_str(), &size);
	if (!data) return;
	const auto faces = ATUIReadFontMetadata(data, size, s_nativeRenderer);
	SDL_free(data);
	for (const auto& face : faces) {
		if (face.requiresNativeRenderer && !s_nativeRenderer) continue;
		ATFontFile rec;
		rec.family = face.family.c_str();
		rec.weight = face.style.c_str();
		rec.italic = face.italic;
		rec.monospaced = face.monospaced;
		rec.fontIndex = face.index;
		rec.path = path;
		s_fontFiles.push_back(std::move(rec));
	}
}

static void ScanFontDir(const VDStringA& dir) {
	// Recursive scan, including nested static font folders. We avoid VDDirectoryIterator
	// dependency and use SDL's enumerator since SDL3 is already linked.
	struct Ctx {
		VDStringA base;
		std::set<VDStringA> visited;
		int depth = 0;
		void Scan(const VDStringA& d) {
			// Limit recursive traversal even if a font directory contains a
			// symlink cycle. OS catalogs normally avoid scanning altogether.
			if (depth >= 32 || visited.size() >= 4096 || !visited.insert(d).second) return;
			++depth;
			SDL_EnumerateDirectoryCallback cb = [](void *ud, const char *dirname, const char *fname) -> SDL_EnumerationResult {
				auto *self = (Ctx *)ud;
				VDStringA full = VDStringA(dirname);
				if (!full.empty() && full[full.size()-1] != '/' && full[full.size()-1] != '\\')
					full += '/';
				full += fname;

				SDL_PathInfo info {};
				if (!SDL_GetPathInfo(full.c_str(), &info))
					return SDL_ENUM_CONTINUE;

				if (info.type == SDL_PATHTYPE_DIRECTORY) {
					self->Scan(full);
				} else if (info.type == SDL_PATHTYPE_FILE) {
					AddFontFiles(full);
				}
				return SDL_ENUM_CONTINUE;
			};
			SDL_EnumerateDirectory(d.c_str(), cb, this);
			--depth;
		}
	} ctx;
	ctx.base = dir;
	ctx.Scan(dir);
}

#ifdef ATUI_HAVE_FONTCONFIG
static bool DiscoverFontconfigFonts() {
	// Query the native service dynamically so portable builds still start
	// on systems without Fontconfig. No additional linked dependency.
	struct Library {
		SDL_SharedObject *handle = SDL_LoadObject("libfontconfig.so.1");
		~Library() { if (handle) SDL_UnloadObject(handle); }
	} library;
	if (!library.handle) return false;
#define ATUI_LOAD_FC(name) \
	auto name = reinterpret_cast<decltype(&::name)>(SDL_LoadFunction(library.handle, #name)); \
	if (!name) return false
	ATUI_LOAD_FC(FcInitLoadConfigAndFonts);
	ATUI_LOAD_FC(FcPatternCreate);
	ATUI_LOAD_FC(FcPatternAddBool);
	ATUI_LOAD_FC(FcObjectSetBuild);
	ATUI_LOAD_FC(FcFontList);
	ATUI_LOAD_FC(FcPatternGetString);
	ATUI_LOAD_FC(FcFontSetDestroy);
	ATUI_LOAD_FC(FcObjectSetDestroy);
	ATUI_LOAD_FC(FcPatternDestroy);
	ATUI_LOAD_FC(FcConfigDestroy);
#undef ATUI_LOAD_FC
	// Fontconfig includes system directories, user-installed fonts, and
	// custom directories configured by the OS. Names/styles come from the
	// font metadata, not filenames; collection faces keep their own index.
	FcConfig *config = FcInitLoadConfigAndFonts();
	if (!config) return false;
	const size_t before = s_fontFiles.size();
	FcPattern *pattern = FcPatternCreate();
	if (pattern) FcPatternAddBool(pattern, FC_SCALABLE, FcTrue);
	FcObjectSet *objects = FcObjectSetBuild(FC_FILE, nullptr);
	FcFontSet *fonts = pattern && objects ? FcFontList(config, pattern, objects) : nullptr;
	if (fonts) {
		for (int i = 0; i < fonts->nfont; ++i) {
			FcPattern *font = fonts->fonts[i];
			FcChar8 *path = nullptr;
			if (FcPatternGetString(font, FC_FILE, 0, &path) == FcResultMatch)
				AddFontFiles(VDStringA((const char *)path));
		}
		FcFontSetDestroy(fonts);
	}
	if (objects) FcObjectSetDestroy(objects);
	if (pattern) FcPatternDestroy(pattern);
	FcConfigDestroy(config);
	return s_fontFiles.size() > before;
}
#endif

static void DiscoverSystemFonts() {
#ifdef ATUI_HAVE_FONTCONFIG
	if (DiscoverFontconfigFonts()) return;
#endif
#if defined(__APPLE__)
	ScanFontDir(VDStringA("/System/Library/Fonts"));
	ScanFontDir(VDStringA("/Library/Fonts"));
	if (const char *home = SDL_getenv("HOME")) {
		VDStringA userDir(home);
		userDir += "/Library/Fonts";
		ScanFontDir(userDir);
	}
#elif defined(__linux__) && !defined(__ANDROID__)
	ScanFontDir(VDStringA("/usr/share/fonts"));
	ScanFontDir(VDStringA("/usr/local/share/fonts"));
	if (const char *dataHome = SDL_getenv("XDG_DATA_HOME")) {
		VDStringA userDir(dataHome);
		userDir += "/fonts";
		ScanFontDir(userDir);
	}
	if (const char *home = SDL_getenv("HOME")) {
		VDStringA userDir(home);
		userDir += "/.fonts";
		ScanFontDir(userDir);
		if (!SDL_getenv("XDG_DATA_HOME")) {
			userDir = home;
			userDir += "/.local/share/fonts";
			ScanFontDir(userDir);
		}
	}
#endif
}

static void RebuildFamilyLists() {
	s_uiFamilies.clear();
	s_monoFamilies.clear();
	for (const auto& f : s_fontFiles) {
		if (std::find(s_uiFamilies.begin(), s_uiFamilies.end(), f.family) == s_uiFamilies.end())
			s_uiFamilies.push_back(f.family);
		if (f.monospaced && std::find(s_monoFamilies.begin(), s_monoFamilies.end(), f.family) == s_monoFamilies.end())
			s_monoFamilies.push_back(f.family);
	}
	std::sort(s_uiFamilies.begin(), s_uiFamilies.end());
	std::sort(s_monoFamilies.begin(), s_monoFamilies.end());
	// If there are no monospaced families discovered, fall back to UI list
	// so the user always has *something* to pick.
	if (s_monoFamilies.empty())
		s_monoFamilies = s_uiFamilies;
}

// Pick the best file for the requested (family, weight) pair.  Falls back
// to Regular weight, then any file in the family, then the role's bundled font.
static const ATFontFile *PickFontFile(const char *family, const char *weight,
	size_t builtinIndex = 0) {
	const ATFontFile *exact = nullptr, *familyRegular = nullptr, *anyInFamily = nullptr;
	for (const auto& f : s_fontFiles) {
		if (f.family != family) continue;
		if (!anyInFamily) anyInFamily = &f;
		if (f.weight == "Regular") familyRegular = &f;
		if (f.weight == weight) { exact = &f; break; }
	}
	if (exact) return exact;
	if (familyRegular) return familyRegular;
	if (anyInFamily) return anyInFamily;
	return s_fontFiles.size() > builtinIndex ? &s_fontFiles[builtinIndex] : nullptr;
}

