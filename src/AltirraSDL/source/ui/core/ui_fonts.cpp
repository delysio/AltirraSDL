class ATSimulator;

// Lists all styles available for a given family, including italics.
static std::vector<VDStringA> CollectWeights(const char *family) {
	std::vector<VDStringA> out;
	for (const auto& f : s_fontFiles) {
		if (f.family != family) continue;
		if (std::find(out.begin(), out.end(), f.weight) == out.end())
			out.push_back(f.weight);
	}
	std::sort(out.begin(), out.end());
	return out;
}

static void RenderFamilyCombo(const char *label,
	const std::vector<VDStringA>& families,
	VDStringA& currentFamily,
	VDStringA& currentWeight, char (&filter)[128])
{
	if (families.empty()) {
		ImGui::TextDisabled("No compatible fonts found.");
		return;
	}
	ImGui::SetNextWindowSizeConstraints(ImVec2(300, 0), ImVec2(FLT_MAX, 420));
	ImGuiContext& g = *GImGui;
	const ImGuiID id = ImGui::GetID(label);
	const bool open = ImGui::BeginCombo(label, currentFamily.c_str(), ImGuiComboFlags_HeightLarge);
	// BeginCombo has no ItemInfo hook in ImGui 1.92. Keep this control
	// discoverable by the UI test engine like the sliders and buttons.
	IMGUI_TEST_ENGINE_ITEM_INFO(id, label, ImGuiItemStatusFlags_Openable
		| (open ? ImGuiItemStatusFlags_Opened : 0));
	if (open) {
		if (ImGui::IsWindowAppearing()) {
			filter[0] = 0;
			ImGui::SetKeyboardFocusHere();
		}
		ImGui::SetNextItemWidth(-1);
		ImGui::InputTextWithHint("##familyFilter", "Filter font families", filter, sizeof filter);
		ImGui::Separator();
		int matches = 0;
		for (const auto& family : families) {
			if (*filter && !SDL_strcasestr(family.c_str(), filter))
				continue;
			++matches;
			if (ImGui::Selectable(family.c_str(), family == currentFamily)) {
				currentFamily = family;
				auto weights = CollectWeights(family.c_str());
				if (std::find(weights.begin(), weights.end(), currentWeight) == weights.end()) {
					currentWeight = weights.empty() ? VDStringA("Regular") : weights.front();
					for (const char *normal : {"Regular", "Book", "Normal"})
						if (std::find(weights.begin(), weights.end(), VDStringA(normal)) != weights.end()) {
							currentWeight = normal;
							break;
						}
				}
				s_dirty = true;
			}
		}
		if (!matches) ImGui::TextDisabled("No matching families.");
		ImGui::EndCombo();
	}
	if (std::find(families.begin(), families.end(), currentFamily) == families.end())
		ImGui::TextDisabled("Selected family is unavailable; using a bundled font.");
}

static void RenderWeightCombo(const char *label, const char *family, VDStringA& currentWeight) {
	auto weights = CollectWeights(family);
	if (weights.empty()) return;

	std::vector<const char *> items;
	items.reserve(weights.size());
	for (const auto& w : weights) items.push_back(w.c_str());

	int idx = -1;
	for (size_t i = 0; i < weights.size(); ++i)
		if (weights[i] == currentWeight) { idx = (int)i; break; }
	if (idx < 0) {
		idx = 0;
		currentWeight = weights[0];
		s_dirty = true;
	}
	ImGuiContext& g = *GImGui;
	const ImGuiID id = ImGui::GetID(label);
	const bool changed = ImGui::Combo(label, &idx, items.data(), (int)items.size(), 16);
	IMGUI_TEST_ENGINE_ITEM_INFO(id, label, ImGuiItemStatusFlags_None);
	if (changed) {
		currentWeight = weights[idx];
		s_dirty = true;
	}
}

void RenderFontsCategory(ATSimulator &) {
	static char uiFilter[128] {}, monoFilter[128] {};
	ImGui::TextWrapped(
		"Choose an installed or bundled font. Use the family filter to find a font "
		"quickly; styles and sizes apply immediately and are saved automatically.");
	ImGui::TextDisabled("%zu font families / %zu monospace families", s_uiFamilies.size(), s_monoFamilies.size());
	if (ImGui::Button("Refresh font list")) {
		DiscoverFonts();
		s_dirty = true;
	}
	ImGui::SetItemTooltip("Reload installed fonts and the fonts folder next to the executable.");
	ImGui::Spacing();

	// ----- UI Font -----
	ImGui::SeparatorText("UI Font");
	ImGui::TextDisabled("Used for menus, dialogs, and text in the emulator UI.");
	RenderFamilyCombo("Family##ui", s_uiFamilies, s_uiFamily, s_uiWeight, uiFilter);
	RenderWeightCombo("Style##ui", s_uiFamily.c_str(), s_uiWeight);
	if (ImGui::SliderInt("Size (pt)##ui", &s_uiSize, 8, 32, "%d pt")) {
		s_dirty = true;
	}
	ImGui::SetItemTooltip("Drag or click; the change applies on the next frame.");

	// Live preview using the currently active font (rebuilt at end of frame).
	if (g_pFontUI) {
		ImGui::PushFont(ATUIGetFontHeading(), ImGui::GetStyle().FontSizeBase * 1.2f);
		ImGui::TextUnformatted("Actions and settings");
		ImGui::PopFont();
		ImGui::PushFont(g_pFontUI);
		ImGui::TextWrapped("The quick brown fox jumps over the lazy dog. 0123456789");
		ImGui::PopFont();
	}
	ImGui::Spacing();

	// ----- Monospace Font -----
	ImGui::SeparatorText("Monospace Font");
	ImGui::TextDisabled(
		"Used for the debugger panes (disassembly, memory, history, console).");
	RenderFamilyCombo("Family##mono", s_monoFamilies, s_monoFamily, s_monoWeight, monoFilter);
	RenderWeightCombo("Style##mono", s_monoFamily.c_str(), s_monoWeight);
	if (ImGui::SliderInt("Size (pt)##mono", &s_monoSize, 8, 32, "%d pt")) {
		s_dirty = true;
	}

	if (g_pFontMono) {
		ImGui::PushFont(g_pFontMono);
		ImGui::TextUnformatted("Preview: lda $D01A   ; 0xDEADBEEF  iiii  WWWW  ....");
		ImGui::PopFont();
	}
	ImGui::Spacing();

	// ----- Reset -----
	ImGui::Separator();
	if (ImGui::Button("Reset to Defaults")) {
		s_uiFamily   = kDefaultUIFamily;
		s_uiWeight   = kDefaultUIWeight;
		s_uiSize     = kDefaultUISize;
		s_monoFamily = kDefaultMonoFamily;
		s_monoWeight = kDefaultMonoWeight;
		s_monoSize   = kDefaultMonoSize;
		s_dirty = true;
	}
	ImGui::SameLine();
	ImGui::TextDisabled("Roboto Medium %d pt / Fira Mono Regular %d pt", kDefaultUISize, kDefaultMonoSize);
}
